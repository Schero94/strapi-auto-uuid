import { describe, expect, it, vi } from 'vitest';
import {
  createUuidInputActions,
  getUuidInputState,
} from '../admin/src/components/Input/actions.js';
import {
  countChanges,
  describeError,
  describeResult,
  summarizeErrors,
} from '../admin/src/utils/report.js';

describe('UUID Content Manager input actions', () => {
  it('emits the Strapi field-change event expected by Content Manager', () => {
    const onChange = vi.fn();
    const actions = createUuidInputActions({
      name: 'publicId',
      type: 'string',
      onChange,
    });

    actions.change('art_123');

    expect(onChange).toHaveBeenCalledWith({
      target: { name: 'publicId', type: 'string', value: 'art_123' },
    });
  });

  it('regenerates only when editing is enabled and field options are valid', () => {
    const onChange = vi.fn();
    const generateValue = vi.fn(() => 'art_generated-v7');
    const actions = createUuidInputActions({
      allowEdit: true,
      options: { version: 'v7', prefix: 'art_' },
      generateValue,
      onChange,
      name: 'publicId',
      type: 'string',
    });

    expect(actions.regenerate()).toBe(true);
    expect(generateValue).toHaveBeenCalledOnce();
    expect(onChange).toHaveBeenCalledWith({
      target: { name: 'publicId', type: 'string', value: 'art_generated-v7' },
    });
  });

  it.each([
    ['manual editing is disabled', false, { version: 'v4', prefix: '' }],
    ['field options are invalid', true, null],
  ])('does not regenerate when %s', (_reason, allowEdit, options) => {
    const onChange = vi.fn();
    const generateValue = vi.fn(() => 'not-written');
    const actions = createUuidInputActions({
      allowEdit,
      options,
      generateValue,
      onChange,
      name: 'publicId',
      type: 'string',
    });

    expect(actions.regenerate()).toBe(false);
    expect(generateValue).not.toHaveBeenCalled();
    expect(onChange).not.toHaveBeenCalled();
  });

  it('copies the current field value and reports clipboard success', async () => {
    const clipboard = { writeText: vi.fn().mockResolvedValue(undefined) };
    const actions = createUuidInputActions({ value: 'art_current-v4', clipboard });

    await expect(actions.copy()).resolves.toBe(true);
    expect(clipboard.writeText).toHaveBeenCalledWith('art_current-v4');
  });

  it('does not copy empty values and contains clipboard failures', async () => {
    const clipboard = { writeText: vi.fn().mockRejectedValue(new Error('denied')) };
    const emptyActions = createUuidInputActions({ value: '', clipboard });
    const deniedActions = createUuidInputActions({ value: 'art_current-v4', clipboard });

    await expect(emptyActions.copy()).resolves.toBe(false);
    expect(clipboard.writeText).not.toHaveBeenCalled();
    await expect(deniedActions.copy()).resolves.toBe(false);
  });
});

describe('UUID Content Manager input state', () => {
  const opts = (overrides = {}) => ({ allowEdit: false, disableAutoGenerate: false, ...overrides });

  it('is read-only and server-generated by default', () => {
    expect(getUuidInputState({ options: opts(), savedValue: '' })).toEqual({
      editable: false,
      canGenerate: false,
      confirmReplace: false,
      placeholder: 'generatedOnSave',
    });
  });

  it('lets a manual-entry field be filled once even when editing is off', () => {
    const manual = opts({ disableAutoGenerate: true });
    expect(getUuidInputState({ options: manual, savedValue: '' })).toMatchObject({
      editable: true,
      placeholder: 'enterManually',
    });
    expect(getUuidInputState({ options: manual, savedValue: 'saved' }).editable).toBe(false);
  });

  it('asks before replacing a saved value and respects the disabled state', () => {
    const editable = opts({ allowEdit: true });
    expect(getUuidInputState({ options: editable, savedValue: 'saved' })).toMatchObject({
      editable: true,
      confirmReplace: true,
    });
    expect(getUuidInputState({ options: editable, savedValue: '', disabled: true }).editable).toBe(
      false
    );
    expect(getUuidInputState({ options: null, savedValue: '' }).editable).toBe(false);
  });
});

describe('repair result summaries', () => {
  it('uses separate preview and applied messages with plural values', () => {
    const preview = describeResult({ dryRun: true, fixed: { duplicates: 2, empty: 1 } });
    expect(preview.map((line) => line.id)).toEqual([
      'field-uuid.report.duplicates.preview',
      'field-uuid.report.empty.preview',
    ]);
    expect(preview[0].values).toEqual({ count: 2 });
    const applied = describeResult({ dryRun: false, fixed: { invalid: 1 } });
    expect(applied[0].id).toBe('field-uuid.report.invalid.applied');
    expect(describeResult({ dryRun: true, fixed: {} })[0].id).toBe('field-uuid.report.nothing');
    expect(countChanges({ totalFixed: 3 })).toBe(3);
    expect(countChanges({ imported: 2 })).toBe(2);
  });

  it('maps server codes and HTTP 409 to translated messages', () => {
    expect(describeError({ response: { status: 409, data: { error: {} } } }).id).toBe(
      'field-uuid.code.REPAIR_IN_PROGRESS'
    );
    expect(describeError({ code: 'TARGET_HAS_VALUE' }).id).toBe('field-uuid.code.TARGET_HAS_VALUE');
    expect(describeError(new Error('x')).id).toBe('field-uuid.code.UNKNOWN');
    expect(summarizeErrors({ errorCounts: { TARGET_NOT_FOUND: 2 } })).toEqual([
      { code: 'TARGET_NOT_FOUND', count: 2 },
    ]);
  });

  it('parses pasted export JSON', async () => {
    const { parseMappings } = await import('../admin/src/utils/parseMappings.js');
    expect(parseMappings('').error).toBe('empty');
    expect(parseMappings('{').error).toBe('json');
    expect(parseMappings('{"a":1}').error).toBe('shape');
    expect(parseMappings('{"mappings":{}}').error).toBeNull();
  });
});
